st.markdown("## 五、常见术语解释")

with st.expander("📖 主升", expanded=False):
    st.markdown("""
    **主升** 是指市场处于强势上涨阶段，热点明确且持续性强。
    - 特征：多个板块连续上涨，资金持续流入
    - 操作建议：积极做多，顺势而为
    """)

with st.expander("📖 轮动", expanded=False):
    st.markdown("""
    **轮动** 是指市场热点快速切换，没有持续性主线。
    - 特征：板块轮番表现，持续时间短
    - 操作建议：低吸潜伏，不宜追高
    """)

with st.expander("📖 退潮", expanded=False):
    st.markdown("""
    **退潮** 是指市场情绪转弱，热点匮乏。
    - 特征：大部分板块下跌，赚钱效应差
    - 操作建议：防守为主，观望等待
    """)

with st.expander("📖 资金轮动", expanded=False):
    st.markdown("""
    **资金轮动** 指资金从前期热点板块撤出，转而流入新的热点板块。
    - 作用：帮助识别资金正在切换的赛道
    - 关注：轮动路径、新主线候选
    """)

with st.expander("📖 生命周期", expanded=False):
    st.markdown("""
    **生命周期** 指板块从启动到退潮的阶段：
    - 启动期：板块刚开始上涨
    - 加速期：板块快速上涨，趋势最强
    - 分歧期：板块开始震荡，多空分歧
    - 退潮期：板块开始下跌
    """)

with st.expander("📖 系统评分", expanded=False):
    st.markdown("""
    **系统评分** 综合评估系统的准确性和可靠性：
    - 识别准确率：主线判断的准确程度
    - 预警命中率：风险预警的有效程度
    - 策略胜率：策略建议的历史表现
    """)

